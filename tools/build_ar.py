"""Build ar/index.html, the Arabic version of the site, from index.html and tools/ar.json.

Search engines only index text that is in the HTML, so the Arabic page is a real file
rather than a language switch in JavaScript. Run this after editing either source file:

    python3 tools/build_ar.py
"""
import json
import re
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://fares.digital"

html = (ROOT / "index.html").read_text(encoding="utf-8")
ar = json.loads((ROOT / "tools" / "ar.json").read_text(encoding="utf-8"))


def replace_once(text, old, new):
    if text.count(old) != 1:
        sys.exit(f"build_ar: expected exactly one match for: {old[:80]}")
    return text.replace(old, new)


def translate(text):
    """Swap the inner HTML of every element with data-i18n="key" for ar[key]."""
    missing = set()
    opens = list(re.finditer(r'<([a-z0-9]+)\b[^>]*\bdata-i18n="([^"]+)"[^>]*>', text))
    for m in reversed(opens):  # from the end, so earlier offsets stay valid
        tag, key = m.group(1), m.group(2)
        if key not in ar:
            missing.add(key)
            continue
        depth, pos = 1, m.end()
        pattern = re.compile(rf"<(/?){tag}\b[^>]*>")
        while depth:
            t = pattern.search(text, pos)
            if not t:
                sys.exit(f"build_ar: no closing </{tag}> for data-i18n=\"{key}\"")
            depth += -1 if t.group(1) else 1
            pos = t.end()
        text = text[: m.end()] + ar[key] + text[t.start() :]
    if missing:
        sys.exit("build_ar: missing Arabic text in tools/ar.json for: " + ", ".join(sorted(missing)))
    return text


def set_meta(text, attr, name, value):
    pattern = rf'(<meta {attr}="{re.escape(name)}" content=")[^"]*(">)'
    text, n = re.subn(pattern, lambda m: m.group(1) + escape(value) + m.group(2), text)
    if n != 1:
        sys.exit(f"build_ar: expected one <meta {attr}=\"{name}\">")
    return text


out = translate(html)
out = replace_once(out, '<!doctype html>\n', "<!doctype html>\n<!-- Generated by tools/build_ar.py from index.html and tools/ar.json. Edit those, then rebuild. -->\n")
out = replace_once(out, '<html lang="en" dir="ltr">', '<html lang="ar" dir="rtl">')
out = re.sub(r"<title>[^<]*</title>", lambda m: f"<title>{escape(ar['_title'])}</title>", out, count=1)
out = set_meta(out, "name", "description", ar["_desc"])
out = set_meta(out, "property", "og:locale", "ar_AR")
out = set_meta(out, "property", "og:locale:alternate", "en_US")
out = set_meta(out, "property", "og:url", f"{SITE}/ar/")
out = set_meta(out, "property", "og:title", ar["_og_title"])
out = set_meta(out, "property", "og:description", ar["_og_desc"])
out = set_meta(out, "property", "og:image:alt", ar["_og_image_alt"])
out = replace_once(out, f'<link rel="canonical" href="{SITE}/">', f'<link rel="canonical" href="{SITE}/ar/">')
out = replace_once(
    out,
    '<a class="lang" id="lang" href="ar/" hreflang="ar" lang="ar">العربية</a>',
    '<a class="lang" id="lang" href="../" hreflang="en" lang="en">English</a>',
)
out = re.sub(r'alt="Portrait of Fares Ashraf[^"]*"', f'alt="{escape(ar["_portrait_alt"])}"', out, count=1)
out = re.sub(r'\b(src|href|poster)="assets/', r'\1="../assets/', out)

(ROOT / "ar").mkdir(exist_ok=True)
(ROOT / "ar" / "index.html").write_text(out, encoding="utf-8")
print("Wrote ar/index.html")
